"""
Generate supabase/migrations/0009_drive_products.sql: the products photographed
in the client's Drive folder (src/lib/drive-products.json) that the stock-sheet
seed (0007) never had, plus the colour/design options read off product photos
(src/lib/photo-variants.json).

Additive only, safe to re-run:
- a product whose slug already exists is left alone;
- options are only added to a product that has none, or whose only option is
  the seed's unpriced "Default" (that one is renamed to the first colour);
- nothing is deleted, and no price or stock an admin has set is touched.

New rows match the rest of the live catalogue: visible, price 0, stock 0.
Drive products go first in their category (negative sort order), as on the
local shop.

    python tools/gen_drive_seed.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIB = ROOT / "src" / "lib"
OUTPUT = ROOT / "supabase" / "migrations" / "0009_drive_products.sql"


def esc(s: str) -> str:
    return s.replace("'", "''")


def main():
    drive = json.loads((LIB / "drive-products.json").read_text(encoding="utf-8"))
    photo = json.loads((LIB / "photo-variants.json").read_text(encoding="utf-8"))

    out = [
        "-- Generated by tools/gen_drive_seed.py. Do not hand-edit: re-run the script.",
        "--",
        "-- Adds the products photographed in the client's Drive folder and the",
        "-- colour options read off product photos. Additive and safe to re-run:",
        "-- existing products, prices and stock are never changed or deleted.",
        "",
        "begin;",
        "",
    ]

    product_rows = []
    total = 0
    for cat, products in drive.items():
        n = len(products)
        for i, p in enumerate(products):
            total += 1
            note = f"{int(p['unitsPerBox'])} per box" if p.get("unitsPerBox") else ""
            product_rows.append(
                f"  ('{esc(cat)}', '{esc(p['slug'])}', '{esc(p['name'])}', '{esc(note)}', {i - n})"
            )

    out += [
        "insert into public.products (category_id, slug, name, description, is_visible, sort_order)",
        "select c.id, v.slug, v.name, v.note, true, v.sort_order",
        "from (values",
        ",\n".join(product_rows),
        ") as v (category, slug, name, note, sort_order)",
        "join public.categories c on c.slug = v.category",
        "on conflict (slug) do nothing;",
        "",
    ]

    # Every Drive product gets its photo colours, or a single Default.
    option_rows = []
    for products in drive.values():
        for p in products:
            labels = [label for label, _ in photo.get(p["slug"], [])] or ["Default"]
            option_rows += [f"  ('{esc(p['slug'])}', '{esc(l)}', {k})" for k, l in enumerate(labels)]
    # Sheet products that only have photo colours.
    drive_slugs = {p["slug"] for ps in drive.values() for p in ps}
    sheet_photo = {s: v for s, v in photo.items() if s not in drive_slugs}

    out += [
        "-- Options for products that have none yet.",
        "insert into public.product_variants (product_id, label, price, stock_qty, is_visible, sort_order)",
        "select p.id, v.label, 0, 0, true, v.sort_order",
        "from (values",
        ",\n".join(option_rows),
        ") as v (slug, label, sort_order)",
        "join public.products p on p.slug = v.slug",
        "where not exists (select 1 from public.product_variants x where x.product_id = p.id);",
        "",
    ]

    if sheet_photo:
        colour_rows = []
        for slug, entries in sheet_photo.items():
            colour_rows += [f"  ('{esc(slug)}', '{esc(label)}', {k})" for k, (label, _) in enumerate(entries)]
        out += [
            "-- Photo colours for stock-sheet products still on the seed's lone,",
            "-- unpriced \"Default\" option: rename it to the first colour, add the rest.",
            "create temporary table photo_colours (slug text, label text, sort_order int) on commit drop;",
            "insert into photo_colours values",
            ",\n".join(colour_rows) + ";",
            "",
            "create temporary table lone_default on commit drop as",
            "select v.id as variant_id, p.id as product_id, p.slug",
            "from public.products p",
            "join public.product_variants v on v.product_id = p.id",
            "where p.slug in (select distinct slug from photo_colours)",
            "  and v.label = 'Default' and v.price = 0",
            "  and (select count(*) from public.product_variants o where o.product_id = p.id) = 1;",
            "",
            "update public.product_variants v",
            "set label = c.label, sort_order = 0",
            "from lone_default d join photo_colours c on c.slug = d.slug and c.sort_order = 0",
            "where v.id = d.variant_id;",
            "",
            "insert into public.product_variants (product_id, label, price, stock_qty, is_visible, sort_order)",
            "select d.product_id, c.label, 0, 0, true, c.sort_order",
            "from lone_default d join photo_colours c on c.slug = d.slug and c.sort_order > 0;",
            "",
        ]

    out += [
        "commit;",
        "",
        "-- Verify:",
        f"--   select count(*) from public.products where sort_order < 0;  -- {total}",
        "--   select p.slug, v.label from public.product_variants v join public.products p on p.id = v.product_id",
        "--     where p.slug = 'alien-grinder' order by v.sort_order;  -- Silver, Black, Blue, Red",
    ]

    OUTPUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT}: {total} products, {len(option_rows)} options, {len(sheet_photo)} sheet products recoloured")


if __name__ == "__main__":
    main()
